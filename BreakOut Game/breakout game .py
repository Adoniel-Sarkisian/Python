import pygame
import random

#______________________________________________________________________________________________________________________________________________________________________

pygame.init()

#______________________________________________________________________________________________________________________________________________________________________

WIDTH, HEIGHT = 800, 600
screen = pygame.display.set_mode((WIDTH, HEIGHT))
pygame.display.set_caption(".: Breakout Game :.")

#______________________________________________________________________________________________________________________________________________________________________

WHITE = (255, 255, 255)
BLACK = (0, 0, 0)
RED = (255, 0, 0)
BLUE = (0, 0, 255)
GREEN = (0, 255, 0)
YELLOW = (255, 255, 0)
COLORS = [RED, BLUE, GREEN]

#______________________________________________________________________________________________________________________________________________________________________

paddle_width, paddle_height = 120, 15
paddle_x = (WIDTH - paddle_width) // 2 
paddle_y = HEIGHT - 40  
paddle_speed = 12 

#______________________________________________________________________________________________________________________________________________________________________

ball_radius = 10
ball_x = WIDTH // 2
ball_y = HEIGHT // 2
ball_speed_x = 4 * random.choice([-1, 1])
ball_speed_y = -4

#______________________________________________________________________________________________________________________________________________________________________

brick_rows = 5
brick_cols = 8
brick_width = WIDTH // brick_cols - 5
brick_height = 30
bricks = []

#______________________________________________________________________________________________________________________________________________________________________

for row in range(brick_rows):
    for col in range(brick_cols):
        bricks.append(pygame.Rect(col * (brick_width + 5), row * (brick_height + 5), brick_width, brick_height))
#______________________________________________________________________________________________________________________________________________________________________
        
clock = pygame.time.Clock()  
running = True 
score = 0

#______________________________________________________________________________________________________________________________________________________________________

while running:
    screen.fill(BLACK)

    for event in pygame.event.get():
        if event.type == pygame.QUIT:
            running = False

#______________________________________________________________________________________________________________________________________________________________________

    keys = pygame.key.get_pressed()  
    if keys[pygame.K_LEFT] and paddle_x > 0:
        paddle_x -= paddle_speed 
    if keys[pygame.K_RIGHT] and paddle_x < WIDTH - paddle_width:  
        paddle_x += paddle_speed

#______________________________________________________________________________________________________________________________________________________________________

    ball_y += ball_speed_y
    ball_x += ball_speed_x
    
#______________________________________________________________________________________________________________________________________________________________________

    if ball_x <= 0 or ball_x >= WIDTH - ball_radius * 2: 
        ball_speed_x *= -1 
    if ball_y <= 0:  
        ball_speed_y *= -1
        
#______________________________________________________________________________________________________________________________________________________________________

    paddle_rect = pygame.Rect(paddle_x, paddle_y, paddle_width, paddle_height)  
    ball_rect = pygame.Rect(ball_x, ball_y, ball_radius * 2, ball_radius * 2)
    if ball_rect.colliderect(paddle_rect): 
        ball_speed_y *= -1

#______________________________________________________________________________________________________________________________________________________________________

    for brick in bricks[:]:  
        if ball_rect.colliderect(brick): 
            bricks.remove(brick) 
            ball_speed_y *= -1  
            score += 10 
            break 
#______________________________________________________________________________________________________________________________________________________________________ 

    if ball_y >= HEIGHT: 
        print("Game Over! Score:", score)  
        running = False

#______________________________________________________________________________________________________________________________________________________________________
        
    pygame.draw.rect(screen, WHITE, paddle_rect)  
    pygame.draw.ellipse(screen, WHITE, ball_rect)  
    for brick in bricks: 
        pygame.draw.rect(screen, random.choice(COLORS), brick)

#_______________________________________________________________________________________________________________________________________________________________________

    pygame.display.update()
    clock.tick(60)

pygame.quit

